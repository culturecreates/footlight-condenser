# frozen_string_literal: true

require "json"

module Distillator
  # Compares final selected statements and exported RDF, optionally normalizing
  # only expected identities of an explicit same-database QA copy.
  class WebsiteShadowParity
    Result = Struct.new(:status, :differences, :graph_diff, keyword_init: true) do
      def passed?
        status == "passed"
      end
    end

    TRACKED = %w[website event_sources webpages statements].freeze
    MAX_EXAMPLES = 20

    def self.call(baseline:, shadow:)
      new(baseline: baseline, shadow: shadow).call
    end

    def initialize(baseline:, shadow:)
      @baseline, @shadow = baseline, shadow
    end

    def call
      raise ArgumentError, "Snapshot schema mismatch" unless @baseline.fetch("schema_version") == @shadow.fetch("schema_version")

      after, graph = normalized_shadow
      differences = TRACKED.each_with_object({}) do |field, result|
        before = @baseline.fetch(field)
        actual = after.fetch(field)
        if before.is_a?(Array) && actual.is_a?(Array)
          before = before.sort_by { |row| JSON.generate(row) }
          actual = actual.sort_by { |row| JSON.generate(row) }
        end
        next if before == actual

        if before.is_a?(Array) && actual.is_a?(Array)
          removed, added = before - actual, actual - before
          result[field] = { removed_count: removed.size, added_count: added.size,
            removed: removed.first(MAX_EXAMPLES), added: added.first(MAX_EXAMPLES) }
        else
          result[field] = { before: before, after: actual }
        end
      end

      graph_diff = Distillator::GraphDiff.call(
        expected_graph: @baseline.fetch("export_jsonld"), actual_graph: graph
      )
      if graph_diff.added_count.positive? || graph_diff.removed_count.positive?
        differences["artsdata_graph"] = {
          added_count: graph_diff.added_count, removed_count: graph_diff.removed_count,
          added: graph_diff.added.first(MAX_EXAMPLES), removed: graph_diff.removed.first(MAX_EXAMPLES)
        }
      end
      Result.new(status: differences.empty? ? "passed" : "failed", differences: differences, graph_diff: graph_diff)
    end

    private

    def cloned_website?
      @shadow["test_copy_origin_seedurl"].present? &&
        @shadow["test_copy_origin_seedurl"] == @baseline.dig("website", "seedurl")
    end

    def normalized_shadow
      return [@shadow, @shadow.fetch("export_jsonld")] unless cloned_website?

      original_seed = @baseline.fetch("website").fetch("seedurl")
      copy_seed = @shadow.fetch("website").fetch("seedurl")
      # Only identities generated by the QA clone service may be rewritten.
      old_to_new_uris = @baseline.fetch("webpages").map { |row| row[1] }.uniq.to_h do |uri|
        [uri, Websites::CreateTestCopy.test_uri(uri, seedurl: copy_seed)]
      end
      new_to_old = old_to_new_uris.invert
      old_sources = @baseline.fetch("event_sources").sort_by { |row| row.fetch("id") }
      new_sources = @shadow.fetch("event_sources").sort_by { |row| row.fetch("id") }
      mapped_sources = new_sources.each_with_index.map do |row, index|
        previous = old_sources[index]
        next row unless previous

        row.merge("id" => previous.fetch("id"), "website_id" => previous.fetch("website_id"))
      end
      source_id_map = new_sources.each_with_index.to_h do |row, index|
        [row.fetch("id"), old_sources[index]&.fetch("id")]
      end

      mapped_website = @shadow.fetch("website").merge(
        "seedurl" => original_seed, "name" => @baseline.fetch("website").fetch("name")
      )
      mapped_pages = @shadow.fetch("webpages").map do |row|
        page = row.dup
        page[0] = new_to_old.fetch(page[0], page[0])
        page[1] = new_to_old.fetch(page[1], page[1])
        page
      end
      mapped_statements = @shadow.fetch("statements").map do |row|
        statement = row.dup
        statement[0] = new_to_old.fetch(statement[0], statement[0])
        statement[1] = new_to_old.fetch(statement[1], statement[1])
        statement[2] = source_id_map.fetch(statement[2], statement[2])
        statement[4] = map_cached_uri(statement[4], new_to_old)
        statement
      end
      # Normalize JSON payload formatting equally; stored Statement.cache is
      # often a JSON array but may also be a plain string.
      baseline_statements = @baseline.fetch("statements").map do |row|
        value = row.dup
        value[4] = map_cached_uri(value[4], {})
        value
      end
      @baseline = @baseline.merge("statements" => baseline_statements)

      export = JSON.generate(map_value(JSON.parse(@shadow.fetch("export_jsonld")), new_to_old))
      [
        @shadow.merge("website" => mapped_website, "event_sources" => mapped_sources,
          "webpages" => mapped_pages, "statements" => mapped_statements),
        export
      ]
    end

    def map_cached_uri(cache, mapping)
      return cache if cache.nil?
      JSON.generate(map_value(JSON.parse(cache), mapping))
    rescue JSON::ParserError
      mapping.fetch(cache, cache)
    end

    def map_value(value, mapping)
      case value
      when String then mapping.fetch(value, value)
      when Array then value.map { |item| map_value(item, mapping) }
      when Hash then value.transform_values { |item| map_value(item, mapping) }
      else value
      end
    end
  end
end
